  function translateBase(s) {
    const map = L === 'pt' ? E2P : P2E;
    const exact = map.get(s);
    if (exact !== undefined) return exact;
    const core = s.trim();
    if (!core || !HAS_LETTER.test(core)) return s;
    let out = core === s ? undefined : map.get(core);
    if (out === undefined) {
      out = memo.get(core);
      if (out === undefined) {
        out = fromRules(core);
        if (memo.size > 3000) memo = new Map();
        memo.set(core, out);
      }
    }
    return core === s ? out : s.replace(core, () => out);
  }
