  function compileRule(src) {
    const parts = src.split(/(%[st])/);
    const kinds = parts.filter((p, i) => i % 2 === 1);
    const body = parts.map((p, i) => (i % 2 === 1 ? '([\\s\\S]+?)' : p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))).join('');
    return { re: new RegExp('^' + body + '$'), kinds };
  }
